    assert.equal(await page.locator('#journey-list .journey-card').nth(1).locator('button').last().isDisabled(), true);
    assert.ok((await page.locator('#journey-list .journey-card').nth(4).boundingBox()).x > (await page.locator('#journey-list .journey-card').nth(7).boundingBox()).x, 'second chapter should reverse direction like a route');
    assert.equal(await page.locator('#journey-tcf-final').isDisabled(), true);
    const unlocked = await browser.newPage();
    await unlocked.goto('file:///home/simo/Desktop/Le-Defi-Francais/index.html');
    await unlocked.evaluate(() => localStorage.setItem('le-defi-francais-progress', JSON.stringify({ streak: 0, mistakes: [], answered: 0, correct: 0, levels: {}, journey: Object.fromEntries(Array.from({ length: 24 }, (_, index) => [index + 1, true])) })));
    await unlocked.reload();
    await unlocked.context().setOffline(true);
    await unlocked.locator('#journey-tcf-final').click();
    assert.equal(await unlocked.locator('#tcf-offline-exam').isVisible(), true);
    assert.equal(await unlocked.locator('#tcf-exam-answers input[type=radio]').count(), 4);
    await unlocked.close();
    assert.equal(await page.locator('#navigation-links .nav-link:visible').count(), 3);
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    assert.ok((await page.locator('#journey-list .journey-node').first().boundingBox()).y < 844, 'first level should peek into the initial mobile viewport');
    const mobileNodes = await page.locator('#journey-list .journey-card').evaluateAll((cards) => cards.slice(0, 4).map((card) => ({ x: card.getBoundingClientRect().x, y: card.getBoundingClientRect().y, width: card.getBoundingClientRect().width })));
    assert.ok(mobileNodes[1].x >= mobileNodes[0].x + mobileNodes[0].width, 'mobile map cards should not overlap');
    assert.ok(mobileNodes[2].y > mobileNodes[0].y, 'mobile map should have two columns');
    assert.ok(mobileNodes[2].x > mobileNodes[3].x, 'mobile route should turn back after level 2');
    await page.setViewportSize({ width: 1440, height: 900 });
    await page.locator('#journey-continue').click();
    assert.equal(await page.locator('#practice-topic').textContent(), 'Les bases · Niveau 1');
    assert.equal(await page.locator('#question-number').textContent(), '1 / 12');
    await page.locator('#leave-practice').click();
    await page.locator('#free-practice summary').click();
    await page.locator('#start-grammar').click();
    assert.equal(await page.locator('#levels-page').isVisible(), true);
    assert.equal(await page.locator('#levels-list article').count(), 4);
    assert.equal(await page.locator('#levels-list article').nth(3).locator('button').isDisabled(), true);
    await page.locator('#levels-list article').first().locator('button').click();
    assert.equal(await page.locator('#question-number').textContent(), '1 / 4');
    await page.locator('#leave-practice').click();
    await page.locator('#start-mixed').click();
    assert.equal(await page.locator('#navigation').isVisible(), true);
    assert.equal(await page.locator('#navigation-links').isVisible(), false);
    assert.equal(await page.locator('.choice').count(), 4);
    assert.ok((await page.locator('.choice').first().boundingBox()).height >= 56, 'answer choices need comfortable click targets');
    await page.keyboard.press('1');
    assert.equal(await page.locator('#answer-area').isVisible(), true);
    assert.ok((await page.locator('.rule').textContent()).length > 30);
    await page.locator('#leave-practice').click();
    await page.locator('#resume-session').click();
    assert.equal(await page.locator('#answer-area').isVisible(), true);
    await page.locator('#navigation-toggle').click();
    await page.locator('#nav-tcf').click();
    assert.equal(await page.locator('#tcf-page').isVisible(), true);
    assert.equal(await page.locator('#tcf-real-exam').isVisible(), true);
    await page.context().setOffline(true);
    await page.locator('#tcf-real-exam').click();
    assert.equal(await page.locator('#tcf-offline-exam').isVisible(), true);
    assert.equal(await page.locator('#navigation-links').isVisible(), false);
    assert.equal(await page.locator('#tcf-exam-answers input[type=radio]').count(), 4);
    assert.equal(await page.locator('#tcf-exam-question-number').textContent(), 'Question 1 / 80');
    assert.match(await page.locator('#tcf-exam-document').getAttribute('src'), /^tcf-offline\/.*\.pdf#page=3$/);
    await page.locator('#tcf-exam-answers input[type=radio]').first().check();
    assert.match(await page.locator('#tcf-exam-progress').textContent(), /1 \/ 80/);
    assert.match(await page.locator('#tcf-exam-audio').getAttribute('src'), /^tcf-offline\//);
    await page.locator('#tcf-exam-next').click();
    assert.equal(await page.locator('#tcf-exam-question-number').textContent(), 'Question 2 / 80');
    await page.locator('#tcf-exam-previous').click();
    assert.equal(await page.locator('#tcf-exam-answers input[value=A]').isChecked(), true);
    await page.reload();
    await page.locator('#nav-tcf').click();
    await page.locator('#tcf-real-exam').click();
    assert.equal(await page.locator('#tcf-exam-answers input[value=A]').isChecked(), true);
    await page.locator('#tcf-exam-jump').click();
    await page.locator('#tcf-exam-jump-list button').nth(40).click();
    assert.equal(await page.locator('#tcf-exam-question-number').textContent(), 'Question 41 / 80');
    assert.match(await page.locator('#tcf-exam-document').getAttribute('src'), /tcf17-livret-complet\.pdf#page=3$/);
    await page.reload();
    await page.locator('#nav-tcf').click();
    await page.locator('#tcf-real-exam').click();
    assert.equal(await page.locator('#tcf-exam-question-number').textContent(), 'Question 41 / 80');
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
