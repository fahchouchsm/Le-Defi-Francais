    assert.equal(await page.locator('#tcf-exam-answers').isVisible(), true);
    assert.equal(await page.locator('#tcf-exam-document').isVisible(), false);
    await page.locator('#tcf-exam-view-document').click();
    assert.equal(await page.locator('#tcf-exam-document').isVisible(), true);
    await page.setViewportSize({ width: 1440, height: 900 });
